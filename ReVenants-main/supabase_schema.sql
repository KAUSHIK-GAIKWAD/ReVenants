    -- ReVenants database schema for Supabase (PostgreSQL).
    -- Run this once in Supabase SQL Editor before starting the application.

    create table if not exists participants (
        id text primary key,
        name text not null,
        telegram_id bigint unique,
        telegram_handle text,
        created_at timestamptz not null default now()
    );

    create table if not exists tasks (
        task_id text primary key,
        title text not null,
        description text,
        owner_id text not null references participants(id),
        status text not null default 'Pending'
            check (status in ('Pending', 'In Progress', 'Blocked', 'Complete')),
        progress_percent integer not null default 0
            check (progress_percent between 0 and 100),
        blocker text,
        due_date date not null,
        priority text not null default 'Medium'
            check (priority in ('Low', 'Medium', 'High', 'Urgent')),
        depends_on_task_id text references tasks(task_id),
        reminder_count integer not null default 0,
        created_at timestamptz not null default now(),
        updated_at timestamptz not null default now()
    );

    create table if not exists messages (
        id bigint generated by default as identity primary key,
        telegram_message_id bigint,
        sender_id text references participants(id),
        task_id text references tasks(task_id),
        direction text not null check (direction in ('inbound', 'outbound')),
        content text not null,
        timestamp timestamptz not null default now()
    );

    create table if not exists status_history (
        id bigint generated by default as identity primary key,
        task_id text not null references tasks(task_id),
        previous_status text not null,
        new_status text not null,
        changed_by_message text not null,
        trigger_source text not null default 'telegram_reply',
        confidence double precision check (confidence between 0 and 1),
        changed_at timestamptz not null default now()
    );

    create index if not exists tasks_status_idx on tasks(status);
    create index if not exists tasks_due_date_idx on tasks(due_date);
    create index if not exists messages_task_id_idx on messages(task_id);
    create index if not exists status_history_task_id_idx on status_history(task_id);

    create or replace function prevent_status_history_mutation()
    returns trigger
    language plpgsql
    as $$
    begin
        raise exception 'status_history is append-only';
    end;
    $$;

    drop trigger if exists status_history_append_only on status_history;
    create trigger status_history_append_only
    before update or delete on status_history
    for each row execute function prevent_status_history_mutation();

    -- Enable RLS before exposing tables through a browser client. The server-side
    -- worker should use a protected key and explicit policies should be added
    -- once the dashboard authentication model is implemented.
    alter table participants enable row level security;
    alter table tasks enable row level security;
    alter table messages enable row level security;
    alter table status_history enable row level security;
